<?php

/*
 * Test how the ID for a new row is chosen:
 * - if the table can generate an ID in code, it does so, even if the database could generate one too.
 * - if neither the code nor the database can generate one, a missing ID is rejected as soon as the object is made.
 */

use Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData;
use Ramsey\Uuid\Uuid;

class TestIdGenerationPreference
{
    public function __construct()
    {
        $db = ConnectionHandler::getDb();
        $db->query("TRUNCATE {$db->escapeIdentifier("event")}, {$db->escapeIdentifier("tag")}");
        EventTable::getInstance()->emptyCache();
        TagTable::getInstance()->emptyCache();
    }


    public function run() : void
    {
        $this->testCodeGenerationIsPreferred();
        $this->testNoIdSourceIsRejected();
    }


    private function testCodeGenerationIsPreferred() : void
    {
        // the database default makes v4 UUIDs, whereas the code makes v7, so the version shows where it came from.
        $created = EventTable::getInstance()->insert(['name' => 'created']);
        $saved = EventRecord::createNewFromArray(['name' => 'saved']);
        $saved->save();
        $cloned = clone $created;

        foreach (['insert()' => $created, 'save()' => $saved, 'clone' => $cloned] as $source => $event)
        {
            $version = Uuid::fromString($event->getId())->getFields()->getVersion();

            if ($version !== 7)
            {
                throw new \Exception("The ID from {$source} was a v{$version} UUID, so was not generated in code.");
            }
        }
    }


    private function testNoIdSourceIsRejected() : void
    {
        // tags can't have their IDs generated by the code or the database, so they must always be provided.
        $providedTag = TagTable::getInstance()->insert(['id' => 'provided', 'name' => 'provided']);

        if ($providedTag->getId() !== 'provided')
        {
            throw new \Exception("insert() did not use the provided ID.");
        }

        $callsThatMustBeRejected = [
            'insert()'             => function () : void { TagTable::getInstance()->insert(['name' => 'no id']); },
            'createNewFromArray()' => function () : void { TagRecord::createNewFromArray(['name' => 'no id']); },
            'clone'                => function () use ($providedTag) : void { $clone = clone $providedTag; },
        ];

        foreach ($callsThatMustBeRejected as $source => $call)
        {
            $rejected = false;

            try
            {
                $call();
            }
            catch (ExceptionMissingRequiredData)
            {
                $rejected = true;
            }

            if ($rejected === false)
            {
                throw new \Exception("{$source} did not reject a missing ID that nothing could generate.");
            }
        }
    }
}

<?php

/*
 * This class represents a single row in a table. E.g. each row in a table can
 * be turned into one of these and interacted with.
 */

declare(strict_types = 1);

namespace Programster\PgsqlObjects;


use Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData;
use Programster\PgsqlObjects\Exceptions\ExceptionObjectDeleted;
use Programster\PgsqlObjects\Exceptions\ExceptionUnknownColumn;

/**
 * @template T of \Programster\PgsqlObjects\AbstractTableRowObject
 */
abstract class AbstractTableRowObject
{
    // the identifier, e.g. a UUID string or a SERIAL int. Null until the database generates it, for tables whose IDs
    // are generated by the database.
    protected int|string|null $m_id;
    protected bool $m_isSavedInDatabase = false;

    // set by delete(), after which the object can't be saved or updated, so its row can't be re-inserted by mistake.
    protected bool $m_isDeleted = false;


    /**
     * Constructor with no parameters and declared final so cannot be overridden.
     * If you need to create other ways of creating the object, then create a new createXyz method.
     */
    final protected function __construct()
    {
        $this->m_id = null;
        $this->m_isSavedInDatabase = false;
        $this->m_isDeleted = false;
    }


    /**
     * Create this object from a row in the database.
     * WARNING - do not use this method to create new objects that don't exist in the database, instead, if you
     * wish to do that, call createNewFromArray() instead.
     *
     * @param array $row - the row, which must include the ID column, as a row in the database always has an ID.
     *
     * @param ?array $fieldInfoMap - optional array of field info, from the table's getFieldInfoMap() (in the same form
     * as pg_meta_data() returns), used to convert the values to the right PHP types.
     *
     * @return static
     *
     * @throws \Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData - if the row has no ID, or is missing
     * other required name/value pairs that this object gets created from.
     *
     * @throws ExceptionUnknownColumn - if the row has a column that this object has no setter for. If the row came from
     * a custom query, select only the table's columns.
     */
    public static function createFromDatabaseRow(array $row, ?array $fieldInfoMap = null) : static
    {
        $object = new static();
        $idColumnName = $object->getTableHandler()->getIdColumnName();

        // never generate an ID here, as this object is for a row that already exists with its own ID.
        if (!isset($row[$idColumnName]))
        {
            throw new ExceptionMissingRequiredData(
                "Can't create a " . static::class . " from a database row that has no {$idColumnName}. If the" .
                " row came from a custom query, make sure it selects the {$idColumnName} column."
            );
        }

        $object->initializeFromArray($row, $fieldInfoMap);
        $object->m_isSavedInDatabase = true;
        return $object;
    }


    /**
     * Create a new object for possibly saving to the database later. Use this method instead of createFromDatabaseRow
     * when you want to create new records. If no ID is given, one is generated in code if the table can do so,
     * otherwise the object has no ID until it is saved and the database generates one.
     * WARNING - this does NOT automatically save to the database. You will need to call ->save() or do something else.
     *
     * @param array $data - the data in the form that it would be if retrieved from the database.
     *
     * @return static - the newly created object.
     *
     * @throws \Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData - if the data array is missing required
     * name/value pairs, or has no ID when neither the code nor the database can generate one.
     *
     * @throws ExceptionUnknownColumn - if the data has a key that is neither the ID column nor one this object has a
     * setter for, which is usually a typo.
     */
    public static function createNewFromArray(array $data) : static
    {
        $object = new static();
        $tableHandler = $object->getTableHandler();
        $idColumnName = $tableHandler->getIdColumnName();

        // this is the only place a new object gets an ID generated, apart from cloning.
        if (!isset($data[$idColumnName]))
        {
            if ($tableHandler->canCodeGenerateId())
            {
                $data[$idColumnName] = $tableHandler->generateId();
            }
            else
            {
                $object->assertDatabaseCanGenerateId();
                $data[$idColumnName] = null; // the database will generate it when the object is saved.
            }
        }

        $object->initializeFromArray($data);
        $object->m_isSavedInDatabase = false;
        return $object;
    }


    /**
     * Return an object that can be used to interface with the table in a generic way.
     * E.g. delete(id) load(id), and search()
     *
     * @return TableInterface
     */
    public abstract function getTableHandler() : TableInterface;


    /**
     * Deletes this object's row from the database, and marks the object as deleted, so that save(), update(),
     * getSaveQuery() and markSaved() throw an ExceptionObjectDeleted from then on, rather than re-inserting the row.
     * The object's data can still be read. To create the row again deliberately, clone the object and save the clone.
     * If the object has no ID yet (its ID is generated by the database, and it hasn't been saved), there is no row to
     * delete, so no query is run, but the object is still marked as deleted. Calling this again does nothing.
     *
     * @return void
     *
     * @throws \Programster\PgsqlLib\Exceptions\ExceptionQueryError
     */
    public function delete() : void
    {
        if ($this->m_isDeleted === false)
        {
            if ($this->m_id !== null)
            {
                $this->getTableHandler()->deleteById($this->m_id);
                $this->m_isSavedInDatabase = false;
            }

            $this->m_isDeleted = true;
        }
    }


    /**
     * Update some of the object's values, and always save the object to the database: its row is updated if the
     * object has been saved before, or inserted if it hasn't (e.g. a new object from createNewFromArray()), just as
     * save() does. Afterwards, this object takes on the values the database returns, such as a SERIAL ID, column
     * defaults and generated columns. Every key is checked before anything is changed, so if one isn't recognised,
     * neither the object nor the database are changed.
     *
     * @param array $data - column name/value pairs to update. This may include the ID column, to change the object's
     * ID (and its row's), in which case any foreign keys referencing the old ID must allow it.
     *
     * @return void
     *
     * @throws ExceptionObjectDeleted - if the object has been deleted.
     *
     * @throws ExceptionUnknownColumn - if a key is neither the ID column nor one this object has a setter for, which
     * is usually a typo.
     */
    public function update(array $data) : void
    {
        if ($this->m_isDeleted)
        {
            throw new ExceptionObjectDeleted("Can't update this " . get_class($this) . ", as it has been deleted.");
        }

        $this->assertKnownColumns($data);
        $originalId = $this->getId();
        $tableHandler = $this->getTableHandler();
        $idColumnName = $tableHandler->getIdColumnName();
        $setters = $this->getSetFunctions();

        foreach ($data as $name => $value)
        {
            if ($name === $idColumnName)
            {
                // for a saved object, updateById() below changes the row's ID to this, as it's updated by its original
                // ID. For an unsaved one, the row is inserted with it.
                $this->m_id = $value;
            }
            else
            {
                $setter = $setters[$name];
                $setter($value);
            }
        }

        if ($this->m_isSavedInDatabase)
        {
            $updatedObject = $tableHandler->updateById($originalId, $this->getDatabaseArrayForm());
            $this->initializeFromArray($updatedObject->getArrayForm());

            // make this object the cached one for its row, rather than the copy the table built from its reply.
            $tableHandler->cacheObject($this);
        }
        else
        {
            // it has never been saved, so there's no row to update yet: insert it instead.
            $this->save();
        }
    }


    /**
     * Saves this object to the database: its row is updated if the object has been saved before, or inserted if it
     * hasn't (e.g. a new object from createNewFromArray()). Afterwards, this object takes on the values the database
     * returns, such as a SERIAL ID, column defaults and generated columns.
     *
     * @return void
     *
     * @throws ExceptionObjectDeleted - if the object has been deleted. Clone it to save it as a new row.
     */
    public function save() : void
    {
        if ($this->m_isDeleted)
        {
            throw new ExceptionObjectDeleted("Can't save this " . get_class($this) . ", as it has been deleted.");
        }

        $row = $this->getDatabaseArrayForm();

        // either way, take on the values the database generated, such as a SERIAL ID, column defaults, or generated
        // columns.
        if ($this->m_isSavedInDatabase)
        {
            $savedObject = $this->getTableHandler()->updateById($this->m_id, $row);
        }
        else
        {
            $savedObject = $this->getTableHandler()->insert($row);
        }

        $this->initializeFromArray($savedObject->getArrayForm());
        $this->m_isSavedInDatabase = true;

        // make this object the cached one for its row, rather than the copy the table built from its reply.
        $this->getTableHandler()->cacheObject($this);
    }


    /**
     * Returns the relevant query for saving this object to the database, depending on whether the object
     * already exists in the database or not.
     *
     * @return string
     *
     * @throws ExceptionObjectDeleted - if the object has been deleted, which also stops batchSave() saving it.
     */
    public function getSaveQuery() : string
    {
        if ($this->m_isDeleted)
        {
            throw new ExceptionObjectDeleted("Can't save this " . get_class($this) . ", as it has been deleted.");
        }

        return ($this->m_isSavedInDatabase) ? $this->getUpdateQuery() : $this->getInsertQuery();
    }


    /**
     * Mark this object as having been saved in the database.
     * Warning - this should only really ever be called by the table handler. If you manually call this, you
     * may need to be careful taking into account the table handlers object cache.
     *
     * @return void
     *
     * @throws ExceptionObjectDeleted - if the object has been deleted.
     */
    public function markSaved() : void
    {
        if ($this->m_isDeleted)
        {
            $className = get_class($this);
            throw new ExceptionObjectDeleted("Can't mark this {$className} as saved, as it has been deleted.");
        }

        $this->m_isSavedInDatabase = true;
    }


    /**
     * When cloning objects create a new identifier for the object, and make sure to set the flag stating that it
     * is not already saved to the database. If the ID can only be generated by the database, the clone has no ID
     * until it is saved. The clone of a deleted object is not deleted, so it can be saved as a new row.
     *
     * @return void
     *
     * @throws \Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData - if neither the code nor the
     * database can generate an ID, as the clone could never be saved.
     */
    public function __clone() : void
    {
        if ($this->getTableHandler()->canCodeGenerateId())
        {
            $this->m_id = $this->getTableHandler()->generateId();
        }
        else
        {
            $this->assertDatabaseCanGenerateId();
            $this->m_id = null; // the database will assign one when the clone is saved.
        }

        $this->m_isSavedInDatabase = false;
        $this->m_isDeleted = false;
    }


    /**
     * Get this object in array form. This will be keyed by the column names
     * and have values of what is in the database. This is in its "raw" form and
     * may not be suitable for returning in an API response where some things may
     * need to be filtered out (such as passwords) or formatted (such as unix timestamps).
     *
     * @return array
     */
    public function getArrayForm() : array
    {
        $arrayForm = [];
        $arrayForm[$this->getTableHandler()->getIdColumnName()] = $this->m_id;
        $accessors = $this->getAccessorFunctions();

        foreach ($accessors as $columnName => $callback)
        {
            $arrayForm[$columnName] = $callback();
        }

        return $arrayForm;
    }


    /**
     * Fetches an array of database column name to getter closures for this object, allowing us
     * to get the value of each column.
     *
     * @return Array<\Closure>
     */
    protected abstract function getAccessorFunctions() : array;


    /**
     * Fetches an array of database column name to setter closures for this object, allowing us
     * to set the value of each column.
     *
     * @return Array<\Closure>
     */
    protected abstract function getSetFunctions() : array;


    /**
     * Get this object in an array form appropriate for inserting into the database.
     * E.g the indexes are the names of the columns in the databse etc.
     * The virtual fields (see getVirtualFields()) are left out, as PostgreSQL rejects any value for them.
     *
     * @return array
     */
    protected function getDatabaseArrayForm() : array
    {
        $properties = [];
        $getFuncs = $this->getAccessorFunctions();
        $virtualFields = $this->getTableHandler()->getVirtualFields();

        foreach ($getFuncs as $columnName => $callback)
        {
            /* @var $callback \Closure */
            if (!in_array($columnName, $virtualFields))
            {
                $properties[$columnName] = $callback();
            }
        }

        if ($this->m_id !== null)
        {
            $properties[$this->getTableHandler()->getIdColumnName()] = $this->m_id;
        }

        return $properties;
    }


    /**
     * Helper to the constructor. Create this object from the passed in inputs.
     *
     * @param array $row - name value pairs of column to values. Must include the ID column, although its value may be
     * null for a new object whose ID the database will generate. This never generates an ID itself.
     *
     * @param ?array $fieldInfoMap - optional array of field info. Should have key of name of field and a value array
     * that contains "type". E.g. https://www.php.net/manual/en/function.pg-meta-data.php
     *
     * @return void
     *
     * @throws \Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData - if the provided row is missing a
     * required key/column, including the ID column.
     */
    protected function initializeFromArray(array $row, ?array $fieldInfoMap = null) : void
    {
        $this->assertKnownColumns($row);

        $intFieldTypes = [
            "int2", // smallint
            "int4", // integer or serial
            "int8", // bigint or bigserial
        ];

        // money is deliberately not converted, as the database returns it formatted for its locale
        // (e.g. "$12.34"), which floatval() would turn into 0.
        $floatFieldTypes = [
            "numeric",
            "float4", // real
            "float8", // double precision
        ];

        $boolFieldTypes = [
            "bool"
        ];

        $idColumnName = $this->getTableHandler()->getIdColumnName();

        if (array_key_exists($idColumnName, $row) === false)
        {
            throw new ExceptionMissingRequiredData(
                "Trying to create a " . get_class($this) . " from an array that has no {$idColumnName} column."
            );
        }

        $fieldsToKeepAsString = $this->getTableHandler()->getFieldsToKeepAsString();
        $id = $row[$idColumnName];

        // convert integer IDs (e.g. SERIAL) to ints, as the database returns every value as a string.
        if (
               $id !== null
            && $fieldInfoMap !== null
            && isset($fieldInfoMap[$idColumnName])
            && in_array($fieldInfoMap[$idColumnName]['type'], $intFieldTypes)
            && !in_array($idColumnName, $fieldsToKeepAsString)
        )
        {
            $id = intval($id);
        }

        $this->m_id = $id;
        $setMethods = $this->getSetFunctions();

        foreach ($setMethods as $columnName => $callback)
        {
            /* @var $callback \Closure */
            if (array_key_exists($columnName, $row) === false)
            {
                if (
                       !in_array($columnName, $this->getTableHandler()->getFieldsThatAllowNull())
                    && !in_array($columnName, $this->getTableHandler()->getFieldsThatHaveDefaults())
                    && !in_array($columnName, $this->getTableHandler()->getVirtualFields())
                )
                {
                    $errMsg =
                        "Trying to create a new " . get_class($this) . " from an array, but missing required column:" .
                        " $columnName. That column is required because it is not marked as allowing null, having" .
                        " a default value, or being generated by the database.";

                    throw new ExceptionMissingRequiredData($errMsg);
                }
            }
            else
            {
                $value = $row[$columnName];

                if (
                       $fieldInfoMap !== null
                    && isset($fieldInfoMap[$columnName])
                    && !in_array($columnName, $fieldsToKeepAsString)
                )
                {
                    $fieldType = $fieldInfoMap[$columnName]['type'];

                    if (in_array($fieldType, $floatFieldTypes))
                    {
                        if ($value !== null)
                        {
                            $value = floatval($value);
                        }

                        $callback($value);
                    }
                    else if (in_array($fieldType, $intFieldTypes))
                    {
                        if ($value !== null)
                        {
                            $value = intval($value);
                        }

                        $callback($value);
                    }
                    else if (in_array($fieldType, $boolFieldTypes))
                    {
                        if ($value !== null)
                        {
                            $value = ($value === "t"); // value is string "t" or "f" for true or false.
                        }

                        $callback($value);
                    }
                    else
                    {
                        $callback($value);
                    }
                }
                else
                {
                    $callback($value);
                }
            }
        }
    }


    /**
     * Check that the database can generate an ID for a new row that has none, because the code can't.
     *
     * @return void
     *
     * @throws \Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData - if the database can't generate one
     * either, as the row could then never be saved.
     */
    private function assertDatabaseCanGenerateId() : void
    {
        if ($this->getTableHandler()->canDatabaseGenerateId() === false)
        {
            $idColumnName = $this->getTableHandler()->getIdColumnName();

            throw new ExceptionMissingRequiredData(
                "No {$idColumnName} was provided for the new " . get_class($this) . ", and its table can't generate" .
                " one in code, nor does the database generate one."
            );
        }
    }


    /**
     * Check that every key in the data is a column this object knows: its ID column, or one it has a setter for.
     *
     * @param array $data - column name/value pairs.
     *
     * @return void
     *
     * @throws ExceptionUnknownColumn - if any key isn't one of those, listing every such key.
     */
    private function assertKnownColumns(array $data) : void
    {
        $knownColumns = array_keys($this->getSetFunctions());
        $knownColumns[] = $this->getTableHandler()->getIdColumnName();
        $unknownColumns = array_diff(array_keys($data), $knownColumns);

        if (count($unknownColumns) > 0)
        {
            $unknownColumnsList = implode(", ", $unknownColumns);

            throw new ExceptionUnknownColumn(
                get_class($this) . " has no column(s) called: {$unknownColumnsList}. Its columns are: " .
                implode(", ", $knownColumns) . "."
            );
        }
    }


    /**
     * Get the query that could be used to update this object in the database.
     *
     * @return string
     *
     * @throws \Programster\PgsqlLib\Exceptions\ExceptionUnexpectedValueType - if there was an issue performing the
     * required escaping of the data.
     */
    private function getUpdateQuery() : string
    {
        $row = $this->getDatabaseArrayForm();
        $tableHandler = $this->getTableHandler();
        $db = $tableHandler->getDb();

        $query =
            "UPDATE {$tableHandler->getEscapedQualifiedTableName()} SET " .
            $db->generateQueryPairs($row) .
            " WHERE {$db->generateQueryPairs([$tableHandler->getIdColumnName() => $this->m_id])}";

        return $query;
    }


    /**
     * Get the query that could be used to insert this object into the database.
     * @return string
     */
    private function getInsertQuery() : string
    {
        $tableHandler = $this->getTableHandler();
        $db = $tableHandler->getDb();
        $row = $this->getDatabaseArrayForm();
        $columnNames = array_keys($row);
        $values = array_values($row);
        $escapedColumnNames = $db->escapeIdentifiers($columnNames);
        $escapedValues = $db->escapeValues($values); // null values come back as NULL
        $valuesString = implode(", ", $escapedValues);

        $query =
            "INSERT INTO {$tableHandler->getEscapedQualifiedTableName()}" .
            " (" . implode(",", $escapedColumnNames) . ")" .
            " VALUES ($valuesString)";

        return $query;
    }


    # Accessors
    public function getId() : int|string|null { return $this->m_id; }
    public function isSavedInDatabase() : bool { return $this->m_isSavedInDatabase; }
    public function isDeleted() : bool { return $this->m_isDeleted; }
}

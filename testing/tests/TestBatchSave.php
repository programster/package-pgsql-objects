<?php

/*
 * Test batchSave():
 * - it inserts new objects and updates existing ones.
 * - objects without an ID get one generated in code, if their table can.
 * - objects without an ID whose table can't generate one in code are rejected before anything is saved.
 */

use Programster\PgsqlObjects\Exceptions\ExceptionMissingRequiredData;

class TestBatchSave
{
    public function __construct()
    {
        $db = ConnectionHandler::getDb();
        $db->query("TRUNCATE {$db->escapeIdentifier("product")}, {$db->escapeIdentifier("ticket")}");
        ProductTable::getInstance()->emptyCache();
        TicketTable::getInstance()->emptyCache();
    }


    public function run() : void
    {
        $this->testInsertsAndUpdates();
        $this->testMissingIdThatCantBeGeneratedIsRejected();
    }


    private function testInsertsAndUpdates() : void
    {
        $table = ProductTable::getInstance();
        $existing = $table->insert(['name' => 'existing']);
        $existing->update(['name' => 'renamed']); // saves straight away, so change it again for the batch below.
        $existingInBatch = $table->load($existing->getId());
        $newProduct = ProductRecord::createNewFromArray(['name' => 'new']);

        $existingInBatch->update(['name' => 'batch renamed']);
        $table->batchSave([$existingInBatch, $newProduct]);

        $getName = function (ProductRecord $product) : ?string { return $product->getName(); };
        $savedProducts = $table->loadIds([$existing->getId(), $newProduct->getId()], false);
        $names = array_map($getName, $savedProducts);
        sort($names);

        if ($names !== ['batch renamed', 'new'])
        {
            $namesList = implode(", ", $names);
            throw new \Exception("batchSave() did not insert and update the expected rows, got: {$namesList}");
        }
    }


    private function testMissingIdThatCantBeGeneratedIsRejected() : void
    {
        // ticket IDs can only be generated by the database.
        $tickets = [
            TicketRecord::createNewFromArray(['title' => 'first']),
            TicketRecord::createNewFromArray(['title' => 'second']),
        ];

        $rejected = false;

        try
        {
            TicketTable::getInstance()->batchSave($tickets);
        }
        catch (ExceptionMissingRequiredData)
        {
            $rejected = true;
        }

        if ($rejected === false)
        {
            throw new \Exception("batchSave() did not reject objects without IDs that can't be generated in code.");
        }

        if (count(TicketTable::getInstance()->loadAll()) !== 0)
        {
            throw new \Exception("batchSave() saved some rows before rejecting the batch.");
        }
    }
}

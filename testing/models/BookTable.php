<?php

use Programster\PgsqlLib\PgSqlConnection;
use Programster\PgsqlObjects\Exceptions\ExceptionIdGeneratedInDatabase;

/**
 * A table whose IDs the database generates (SERIAL), with a foreign key to AuthorTable.
 */
class BookTable extends Programster\PgsqlObjects\AbstractTable
{
    public function getDb() : PgSqlConnection
    {
        return ConnectionHandler::getDb();
    }


    public function getFieldsThatAllowNull() : array
    {
        return [];
    }


    public function getFieldsThatHaveDefaults() : array
    {
        return [];
    }


    public function getVirtualFields() : array
    {
        return [];
    }


    public function getObjectClassName() : string
    {
        return 'BookRecord';
    }


    public function getTableName() : string
    {
        return 'book';
    }


    public function generateId() : never
    {
        throw new ExceptionIdGeneratedInDatabase("Book IDs are generated by the database.");
    }


    public function canCodeGenerateId() : bool
    {
        return false;
    }


    public function canDatabaseGenerateId() : bool
    {
        return true;
    }
}
